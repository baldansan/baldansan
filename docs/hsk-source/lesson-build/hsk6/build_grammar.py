def sandhi(chars, syl):
    for i, c in enumerate(chars):
        if c == "一" and i + 1 < len(chars) and chars[i - 1:i] not in ("第", "统", "唯") and re.match(r"[\u4e00-\u9fff]", chars[i + 1]):
            t = tone_of(syl[i + 1])
            if t == 4: syl[i] = "yí"
            elif t in (1, 2, 3): syl[i] = "yì"
        if c == "不" and i + 1 < len(chars) and re.match(r"[\u4e00-\u9fff]", chars[i + 1]) and tone_of(syl[i + 1]) == 4:
            syl[i] = "bú"
    return syl


