def segment(s):
    """(token, start) жагсаалт: эхлээд албадмал үгс (хамгийн урт), үлдсэнийг jieba-аар."""
    out = []
    i = 0
    buf_start = 0
    def flush(a, b):
        pos = a
        for tk in jieba.lcut(s[a:b], HMM=False):
            out.append((tk, pos)); pos += len(tk)
    while i < len(s):
        hit = next((k for k in FORCED if s.startswith(k, i)), None)
        if hit:
            if buf_start < i: flush(buf_start, i)
            out.append((hit, i)); i += len(hit); buf_start = i
        else:
            i += 1
    if buf_start < len(s): flush(buf_start, len(s))
    return out


def py_sentence(s):
    """Өгүүлбэрийн пиньинь: pypinyin (контекстоор) + үгэнд бүлэглэсэн (албадмал толь + jieba)."""
    raw = pinyin(s, style=Style.TONE, errors=lambda x: list(x))
    chars = list(s)
    syl = [r[0] for r in raw]
    assert len(syl) == len(chars), (s, len(syl), len(chars))
    syl = sandhi(chars, syl)
    toks = []
    for tk, a in segment(s):
        b = a + len(tk)
        if not re.match(r"[\u4e00-\u9fff]", tk[0]):
            if re.match(r"\d", tk[0]):
                toks.append(("w", tk))
            else:
                for ch in tk:
                    toks.append(("p", ch))
            continue
        parts = [(a, b, tk)]
        if len(tk) >= 2 and tk not in OVR and tk not in LEX:
            if tk[-1] in SPLIT_END:
                parts = [(a, b - 1, tk[:-1]), (b - 1, b, tk[-1])]
            if tk[0] in "不没" and tk not in NO_SPLIT_NEG:
                parts = [(a, a + 1, tk[0]), (a + 1, b, tk[1:])] if len(parts) == 1 else \
                        [(a, a + 1, tk[0]), (a + 1, b - 1, tk[1:-1]), (b - 1, b, tk[-1])]
        for (x, y, t) in parts:
            if not t:
                continue
            if t in OVR:
                p = OVR[t]
            else:
                ss = syl[x:y]
                if t == "得" and ss == ["dé"]: ss = ["de"]
                if t == "地" and ss == ["dì"]: ss = ["de"]
                if t == "们": ss = ["men"]
                if len(t) >= 2 and t[-1] == "儿" and t not in ERHUA_KEEP and ss[-1] in ("ér", "er"):
                    ss = ss[:-1]; ss[-1] += "r"
                p = "".join(ss)
                if len(t) == 1: UNKNOWN.add(t)
            if t == "天天" and s[x - 1:x] == "阳":
                p = "tiāntiān"
            toks.append(("w", p))
    res = ""
    for k, t in toks:
        if k == "p":
            res += PUNCT.get(t, t)
        else:
            res += (" " if res and not res.endswith(("“", "(", "/")) else "") + t
    res = res.replace(" /", "/")
    res = re.sub(r"\s+([,.!?;:”)])", r"\1", res)
    res = re.sub(r"([,.!?;:])(?=[^\s”)])", r"\1 ", res)
    res = re.sub(r"\s+", " ", res).strip()
    for a, b in FIXES:
        res = res.replace(a, b)
    res = re.sub(r"(^|[.!?]\s|:\s“|^“)([a-zāáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜ])", lambda m: m.group(1) + m.group(2).upper(), res)
    return res




