def P(zh, forced=None):
    """pinyin string for free text. '|' in zh forces word boundaries (and disables lexicon in that region)."""
    if '|' in zh:
        parts = []
        for chunk in zh.split('|'):
            parts.append(chunk)
        segs = []
        for ch in parts:
            if ch and all(is_han(c) or c in PUNCT_MAP for c in ch) and not any(c in PUNCT_MAP for c in ch):
                segs.append(ch)
            else:
                segs.extend(segment(ch))
    else:
        segs = segment(zh)
    seq, owner = [], []  # items with barriers
    for si, sg in enumerate(segs):
        if sg and is_han(sg[0]):
            if sg == '天天!N':
                its = [{'ch': '天天', 'py': 'Tiāntiān', 'atomic': True}]
            else:
                its = items_for_text(sg, PY_OVR)
            for it in its:
                seq.append(it); owner.append(si)
        else:
            seq.append(None); owner.append(si)
    apply_sandhi(seq)
    out = []
    for si, sg in enumerate(segs):
        its = [seq[k] for k in range(len(seq)) if owner[k] == si and seq[k] is not None]
