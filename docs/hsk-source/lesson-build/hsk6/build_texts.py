# ---------------------------------------------------------------- formatting for token-built sentences
def fmt_pieces(pieces):
    s = ''
    oq = False
    for kind, v in pieces:
        if kind == 'w':
            if s and not s.endswith(' ') and not s.endswith('(') and not oq:
                s += ' '
            oq = False
            s += v
        else:
            if v == '“':
                if s and not s.endswith(' '): s += ' '
                s += '"'
                oq = True
                continue
            elif v == '”':
                s += '"'
            elif v == '（':
                if s and not s.endswith(' '): s += ' '
                s += '('
            elif v == '）':
                s += ')'
            else:
                s += PUNCT_MAP.get(v, v)
            oq = False
    s = re.sub(r'\s+', ' ', s).strip()
    chars, cap = list(s), True
    for k, ch in enumerate(chars):
        if cap and ch.isalpha():
            chars[k] = ch.upper(); cap = False
        elif ch in '.?!':
            cap = True
        elif ch == '"' and (k == 0 or chars[k-1] in ' ('):
            cap = True
    return ''.join(chars)

