def segment(zh):
    """longest-match segmentation of a hanzi string; returns list of segments (str)"""
    segs = []
    i = 0
    n = len(zh)
    while i < n:
        ch = zh[i]
        if not is_han(ch):
            j = i
            while j < n and not is_han(zh[j]) and zh[j] not in PUNCT_MAP:
                j += 1
            if j == i:  # punctuation
                if zh[i:i+2] == '……':
                    segs.append('……'); i += 2
                else:
                    segs.append(ch); i += 1
            else:
                segs.append(zh[i:j]); i = j
            continue
        best = None
        for L in range(min(LEX_MAXLEN, n - i), 1, -1):
            w = zh[i:i+L]
            if all(is_han(c) for c in w) and w in LEX:
                best = w; break
        if best is None:
            best = ch
        segs.append(best); i += len(best)
    return segs


