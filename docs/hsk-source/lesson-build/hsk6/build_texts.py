def rebalance(obj, counter=[0]):
    """rotate correct option position deterministically for check / choice items"""
    if isinstance(obj, dict):
        if isinstance(obj.get('options'), list) and 'answer' in obj and str(obj['answer']).isdigit() and (obj.get('type') == 'choice' or 'question' in obj):
            n = len(obj['options'])
            cur = int(obj['answer'])
            tgt = counter[0] % n
            counter[0] += 1
            if tgt != cur:
                o = obj['options']
                o[cur], o[tgt] = o[tgt], o[cur]
                obj['answer'] = str(tgt)
        for v in obj.values(): rebalance(v)
    elif isinstance(obj, list):
        for v in obj: rebalance(v)
