def items_for_text(text, ovr=None):
    """text of hanzi only -> list of items {ch, py}"""
    ovr = ovr or {}
    if text in ovr:
        return [{'ch': text, 'py': ovr[text], 'atomic': True}]
    sy = syl_list(text)
    chars = list(text)
    assert len(sy) == len(chars), (text, sy)
    return [{'ch': c, 'py': p, 'atomic': False} for c, p in zip(chars, sy)]

def apply_sandhi(seq):
    """seq: list of items or None (barrier). modifies in place."""
    n = len(seq)
    for i, it in enumerate(seq):
        if it is None or it['atomic']: continue
        if it['ch'] == '不' and it['py'] == 'bù':
            nx = seq[i+1] if i+1 < n else None
            if nx is not None and tone_of(nx['py']) == 4:
                it['py'] = 'bú'
        if it['ch'] == '一' and it['py'] == 'yī':
            prev = seq[i-1] if i > 0 else None
            if prev is not None and prev['ch'] in '第统唯同之万专':
                continue
            nx = seq[i+1] if i+1 < n else None
            if nx is not None:
                t = tone_of(nx['py'])
                it['py'] = 'yí' if t == 4 else 'yì'
        # 一 + 不? ignore

def join_items(items):
    out = ''
    for k, it in enumerate(items):
        p = it['py']
        if k > 0 and p[:1] in VOW and not items[k-1]['atomic'] and not it['atomic']:
            out += "'"
        out += p
    return out

