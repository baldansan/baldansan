def build_tokens(spec, sent_zh):
    """spec: space-separated tokens, 'tok=py' overrides. returns tokens list [{zh,py}]"""
    toks = spec.split()
    # items
    seq, owner, ovr_py = [], [], {}
    zhs = []
    for ti, t in enumerate(toks):
        if '=' in t:
            z, p = t.split('=', 1)
            ovr_py[ti] = p
        else:
            z = t
        zhs.append(z)
    assert ''.join(zhs) == sent_zh, ('TOKENS != ZH', ''.join(zhs), sent_zh)
    for ti, z in enumerate(zhs):
        if not is_han(z[0]):
            seq.append(None); owner.append(ti); continue
        if ti in ovr_py:
            its = [{'ch': z, 'py': ovr_py[ti], 'atomic': True}]
        elif z in SC:
            auto = ' '.join(syl_list(z))
            SC_LOG.append((z, SC[z], auto))
            its = [{'ch': z, 'py': SC[z], 'atomic': True}]
        elif z == '朝夕相处':
            its = [{'ch': z, 'py': 'zhāoxī xiāngchǔ', 'atomic': True}]
        else:
            its = items_for_text(z, {})
        for it in its:
            seq.append(it); owner.append(ti)
    apply_sandhi(seq)
    out = []
    for ti, z in enumerate(zhs):
        its = [seq[k] for k in range(len(seq)) if owner[k] == ti and seq[k] is not None]
        if is_han(z[0]):
            out.append({'zh': z, 'py': join_items(erhua(its))})
        else:
            out.append({'zh': z, 'py': ''})
    return out

