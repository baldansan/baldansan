PUNCT = {'，': ',', '、': ',', '。': '.', '？': '?', '！': '!', '：': ':'}
END = '.?!'

def S(spk_zh, spk_py, body, mn, note=None, ks=None):
    """body: 'word|pinyin word|pinyin ，' ; '_' in pinyin = space."""
    toks = [{'zh': spk_zh, 'py': spk_py[0].upper()+spk_py[1:]}, {'zh': '：', 'py': ''}]
    for p in body.split():
        if '|' in p:
            z, y = p.split('|')
            toks.append({'zh': z, 'py': y.replace('_', ' ')})
        else:
            assert p in PUNCT, p
            toks.append({'zh': p, 'py': ''})
    zh = ''.join(t['zh'] for t in toks)
    # pinyin
    out = ''
    cap = False
    for i, t in enumerate(toks):
        if t['zh'] in PUNCT:
            out += PUNCT[t['zh']]
            if t['zh'] == '：':
                out += ' '; cap = True
            elif PUNCT[t['zh']] in END:
                cap = True
                out += ' '
            else:
                out += ' '
            continue
        y = t['py']
        if cap and y:
            y = y[0].upper() + y[1:]
            cap = False
        out += y + ('' if (i + 1 < len(toks) and toks[i+1]['zh'] in PUNCT) else ' ')
    py = out.strip()
    d = {'zh': zh, 'pinyin': py, 'mn': mn, 'tokens': toks}
    if note:
        d['note'] = note
        d['key_structures'] = ks or []
    return d

def PY(body):
    """free sentence (no speaker) -> (zh, pinyin, tokens)"""
    toks = []
    for p in body.split():
        if '|' in p:
            z, y = p.split('|'); toks.append({'zh': z, 'py': y.replace('_', ' ')})
        else:
            toks.append({'zh': p, 'py': ''})
    zh = ''.join(t['zh'] for t in toks)
    out = ''; cap = True
    for i, t in enumerate(toks):
        if t['zh'] in PUNCT:
            out += PUNCT[t['zh']] + ' '
            if PUNCT[t['zh']] in END: cap = True
            continue
        y = t['py']
        if cap: y = y[0].upper() + y[1:]; cap = False
        out += y + ('' if (i + 1 < len(toks) and toks[i+1]['zh'] in PUNCT) else ' ')
    return zh, out.strip()

