-- =============================================================================
-- 069 — «Хувийн багш» (私教): загвар шалгалтын асуулт бүрийн багшийн тайлбар
-- =============================================================================
--
-- ЯАГААД:
-- `explanation_mn` нь нэг догол мөр тайлбар. Суралцагч HSK-д хувийн багштай
-- бэлдэж байгаа юм шиг — «юу гэж хэлсэн, яагаад чи бурууг нь сонгов, алийг
-- нь сонгох ёстой байсан» — гэсэн бүтэцтэй тайлбар хэрэгтэй. Үүнийг нэг
-- jsonb баганад хадгална; UI нь хэсэг бүрийг тусад нь харуулна.
--
-- БҮТЭЦ (lib/mock-test/tutor-note.ts дахь TutorNote-той яг ижил):
-- {
--   "transcript": [ { "zh": "男：…", "pinyin": "…", "mn": "…" }, … ],  -- сонсгол: юу гэж хэлсэн, мөр мөрөөр (zh дотор 男/女 угтвар байж болно)
--   "key":   "…",        -- хариултыг шийдсэн нэг өгүүлбэр/хэллэг (zh)
--   "keyMn": "…",        -- түүний утга (mn)
--   "why":   "…",        -- ЗААВАЛ: зөв сонголт яагаад зөв бэ (mn)
--   "wrong": { "B": "…", "C": "…" }, -- сонголт бүр яагаад буруу вэ (mn)
--   "trap":  "…",        -- асуултын урхи (mn)
--   "tip":   "…",        -- арга зүйн зөвлөгөө (mn)
--   "words": [ { "zh": "…", "pinyin": "…", "mn": "…" }, … ]  -- 3–6 түлхүүр үг
-- }
-- Зөвхөн `why` заавал; бусад нь сонголттой. `tutor_note` null бол UI
-- хуучин `explanation_mn`-ээ харуулна.
--
-- Дахин ажиллуулахад аюулгүй.
-- =============================================================================

alter table public.mock_test_questions
  add column if not exists tutor_note jsonb;

comment on column public.mock_test_questions.tutor_note is
  'Багшийн бүтэцтэй тайлбар (私教讲解). JSON: {transcript?[{zh,pinyin?,mn?}], key?, keyMn?, why, wrong?{A:…}, trap?, tip?, words?[{zh,pinyin,mn}]}. Зөвхөн why заавал. null бол explanation_mn-ээ харуулна.';

-- Тайлбартай асуултыг шалгалтаар нь тоолоход (дасгалын жагсаалтын тэмдэг).
create index if not exists mock_test_questions_tutor_note_idx
  on public.mock_test_questions (test_id)
  where tutor_note is not null;
